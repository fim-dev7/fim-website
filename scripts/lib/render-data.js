import fs from 'fs';

const ESC_MAP = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
function esc(s) { return String(s == null ? '' : s).replace(/[&<>"']/g, c => ESC_MAP[c]); }
function escAttr(s) { return esc(s); }

/**
 * Serialize a JS object literal with double-quoted keys and string values.
 * Booleans, numbers, and nested arrays pass through.
 */
function jsLiteral(v, indent = 2, depth = 0) {
  const pad = ' '.repeat(indent * (depth + 1));
  const padOuter = ' '.repeat(indent * depth);
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'boolean' || typeof v === 'number') return String(v);
  if (typeof v === 'string') return JSON.stringify(v);
  if (Array.isArray(v)) {
    if (v.length === 0) return '[]';
    const items = v.map(x => pad + jsLiteral(x, indent, depth + 1));
    return '[\n' + items.join(',\n') + '\n' + padOuter + ']';
  }
  if (typeof v === 'object') {
    const keys = Object.keys(v);
    if (keys.length === 0) return '{}';
    const props = keys.map(k => `${pad}${k}: ${jsLiteral(v[k], indent, depth + 1)}`);
    return '{\n' + props.join(',\n') + '\n' + padOuter + '}';
  }
  return JSON.stringify(v);
}

function formatShortDate(iso) {
  if (!iso) return '';
  const d = new Date(iso);
  if (isNaN(d.getTime())) return iso;
  return d.toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' });
}

function pickFeatured(episodes, n = 3) {
  const explicit = episodes.filter(e => e.featured);
  if (explicit.length >= n) return explicit.slice(0, n);
  const withPage = episodes
    .filter(e => e.has_episode_page && !e.featured)
    .sort((a, b) => b.episode_number - a.episode_number);
  return [...explicit, ...withPage].slice(0, n);
}

