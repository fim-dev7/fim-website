/**
 * render-homepage-fallback.js — regenerate the crawlable <noscript> homepage.
 *
 * The homepage (/) is the ONE page rendered client-side by React (createRoot in
 * app.jsx); every other page on the site is pre-rendered static HTML. Crawlers /
 * AI bots that don't execute JavaScript therefore see only this <noscript> block
 * when they fetch "/". To keep it from going stale as episodes are added, this
 * script rebuilds the block from the SAME data the React app uses (ARCHIVE +
 * STATS), so the static mirror always matches the live homepage.
 *
 * It rewrites the content between the HOMEPAGE_FALLBACK markers inside index.html.
 * Wired into build-client.mjs, so it runs after every sync.
 *
 * Standalone:  node scripts/lib/render-homepage-fallback.js
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import vm from 'vm';

const START = '<!-- HOMEPAGE_FALLBACK_START -->';
const END = '<!-- HOMEPAGE_FALLBACK_END -->';

const esc = (s) =>
  String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

// Evaluate the two data files (plain JS that declare top-level consts) in a
// sandbox and pull out the globals we need. data-static.jsx defines STATS;
// data.jsx (generated by sync) defines ARCHIVE.
function loadData(root) {
  const sandbox = { window: {}, React: {} };
  vm.createContext(sandbox);
  for (const file of ['data-static.jsx', 'data.jsx']) {
    const src = fs.readFileSync(path.join(root, file), 'utf8').replace('/* global React */', '');
    // expose the declared consts onto the sandbox global for the next file / readout
    vm.runInContext(
      src +
        '\n;globalThis.STATS = typeof STATS !== "undefined" ? STATS : globalThis.STATS;' +
        '\n;globalThis.ARCHIVE = typeof ARCHIVE !== "undefined" ? ARCHIVE : globalThis.ARCHIVE;',
      sandbox,
      { filename: file }
    );
  }
  return { STATS: sandbox.STATS || [], ARCHIVE: sandbox.ARCHIVE || [] };
}

export function buildFallbackHtml(root) {
  const { STATS, ARCHIVE } = loadData(root);
  const count = ARCHIVE.length || 32;

  const statLine = STATS.map((s) => `${esc(s.value)} ${esc(s.label).toLowerCase()}`).join(' · ');

  const episodeItems = ARCHIVE.map(
    (e) =>
      `      <li><a href="${esc(e.url)}">${esc(e.guest)}${e.company ? ' — ' + esc(e.company) : ''}</a></li>`
  ).join('\n');

  // Kept in sync by hand with the copy in sections.jsx (Hero / WhatThisIs / About).
  return `<main style="max-width:820px;margin:0 auto;padding:48px 20px;font-family:system-ui,sans-serif;line-height:1.6;color:#e8e8e8;background:#11201d;">
    <h1>Founders In Motion — before the headline</h1>
    <p><strong>Founders In Motion</strong> is where the top 1% of early-stage founders around the world — across Australia, Southeast Asia, and the US — share how they're building their business: what's working, what's not. Hosted by <strong>Thea Ngo</strong>, an early-stage investor. Think pivots, chaos, scandals, and how to get through it. New episodes weekly.</p>
    <p>${statLine}. Listen on
      <a href="https://open.spotify.com/show/0ZwlHrWLbX6ajZo2hsVVdl">Spotify</a>,
      <a href="https://podcasts.apple.com/us/podcast/founders-in-motion/id1810228671">Apple Podcasts</a>, and
      <a href="https://www.youtube.com/@foundersinmotion">YouTube</a>.</p>

    <h2>What this is</h2>
    <p>Most founder content is about the outcome. Founders In Motion is about the process — what actually happens between the idea and the exit, and why the messy middle is where everything real gets decided. Each episode is one unscripted conversation with one early-stage founder: no pitch, no PR, just the real story of how they found the problem, built the first thing, lost confidence, rebuilt it, and kept going.</p>

    <h2>All ${count} episodes</h2>
    <ul>
${episodeItems}
    </ul>
    <p><a href="/episodes/">Browse all episodes →</a></p>

    <h2>Founder questions, answered</h2>
    <p>Real answers from real founders on the questions people actually ask — how to find your first customers, how to raise a pre-seed round without a product, when to quit your job to start a company, how to do customer discovery on a tiny budget, and how to avoid burning out. <a href="/questions/">Browse all founder questions →</a></p>

    <h2>About the host — Thea Ngo</h2>
    <p>Thea Ngo is an early-stage investor who started Founders In Motion because the highlight reel was driving her crazy — nobody talks about the year of nothing, the co-founder breakup, or the term sheet you walked away from. ${count} episodes deep, she's interviewed founders building non-alcoholic beer, AI robotics ($120M raised), YC companies, chili-oil empires, and next-frontier dating apps. <a href="/about/">More about Thea →</a></p>

    <p>
      <a href="/episodes/">Episodes</a> ·
      <a href="/questions/">Questions</a> ·
      <a href="/topics/">Topics</a> ·
      <a href="/about/">About</a> ·
      <a href="https://www.linkedin.com/in/theango/">LinkedIn</a> ·
      <a href="https://www.instagram.com/thea.yaps">Instagram</a> ·
      <a href="https://www.tiktok.com/@foundersinmotion">TikTok</a>
    </p>
  </main>`;
}

export function renderHomepageFallback(root) {
  const indexPath = path.join(root, 'index.html');
  const html = fs.readFileSync(indexPath, 'utf8');
  const i = html.indexOf(START);
  const j = html.indexOf(END);
  if (i === -1 || j === -1 || j < i) {
    throw new Error(`HOMEPAGE_FALLBACK markers not found in ${indexPath}`);
  }
  const block = buildFallbackHtml(root);
  const next = html.slice(0, i + START.length) + '\n' + block + '\n  ' + html.slice(j);
  if (next !== html) fs.writeFileSync(indexPath, next);
  return { changed: next !== html, episodes: (loadData(root).ARCHIVE || []).length };
}

// Run standalone
if (import.meta.url === `file://${process.argv[1]}`) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
  const r = renderHomepageFallback(root);
  console.log(`homepage <noscript> fallback ${r.changed ? 'updated' : 'unchanged'} — ${r.episodes} episodes`);
}
