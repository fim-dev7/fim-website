// Homepage "Start here" trio — the best-performing episodes, in display order.
// Editorial pick (not recency): edit these slugs to swap which 3 show on the homepage.
const START_HERE_SLUGS = ['4-kiki-and-elan', '24-nam-nguyen', '14-jason-ma'];

export function renderDataCMS({ episodes, settings }) {
  const sortedDesc = [...episodes].sort((a, b) => b.episode_number - a.episode_number);
  // Prefer the curated "Start here" trio; fall back to featured/most-recent if any slug is missing.
  const bySlug = new Map(sortedDesc.map(e => [e.slug, e]));
  const curated = START_HERE_SLUGS.map(s => bySlug.get(s)).filter(Boolean);
  const featured = curated.length === START_HERE_SLUGS.length ? curated : pickFeatured(sortedDesc, 3);

  const EPISODES = featured.map(e => ({
    n: String(e.episode_number),
    title: e.title,
    guest: e.guest_name,
    company: e.guest_company,
    role: e.role || (e.guest_company ? `Founder, ${e.guest_company}` : 'Founder'),
    tags: e.tags || [],
    primaryTag: (e.tags && e.tags[0]) || 'Founders',
    desc: e.short_desc || e.hook || '',
    url: e.has_episode_page ? `episodes/${e.slug}/` : (e.spotify_url || ''),
    dur: e.duration || '',
    date: formatShortDate(e.published_date),
    featured: true,
  }));

  const ARCHIVE = sortedDesc.map(e => {
    const row = { guest: e.guest_name, company: e.guest_company };
    if (e.has_episode_page) row.url = `episodes/${e.slug}/`;
    return row;
  });

  const PLATFORMS = [
    { name: 'Spotify',         short: 'SP', url: settings.spotify_show   || 'https://open.spotify.com/show/0ZwlHrWLbX6ajZo2hsVVdl', color: '#1DB954' },
    { name: 'Apple Podcasts',  short: 'AP', url: settings.apple_show     || 'https://podcasts.apple.com/us/podcast/founders-in-motion/id1810228671', color: '#FC3C44' },
    { name: 'YouTube',         short: 'YT', url: settings.youtube_channel|| '#', color: '#FF0000' },
    { name: 'Instagram',       short: 'IG', url: settings.instagram      || 'https://www.instagram.com/thea.yaps', color: '#D4A87D' },
  ];

  const generatedAt = new Date().toISOString();

  return `/* global React */
/* GENERATED by scripts/sync.js — DO NOT EDIT BY HAND. */
/* Hand-curated content (FAQ, QUOTES, STATS, FEATURES, FILTERS) lives in data-static.jsx */
/* Generated: ${generatedAt} */

const EPISODES = ${jsLiteral(EPISODES)};

const FEATURED = EPISODES[0];

const ARCHIVE = ${jsLiteral(ARCHIVE)};

const PLATFORMS = ${jsLiteral(PLATFORMS)};

Object.assign(window, { EPISODES, FEATURED, ARCHIVE, PLATFORMS });
`;
}

